RC4_KEY  = b"rOIBXiPtf9"
OUT_IDC  = r"C:\Users\unina\Desktop\StealC\bin\stealc\Ida\stealc_annotate.idc"
OUT_TXT  = r"C:\Users\unina\Desktop\StealC\bin\stealc\Ida\stealc_strings.txt"
